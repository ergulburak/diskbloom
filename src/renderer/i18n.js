// file:// pages get no localStorage in Electron, so the choice is saved by the main process.
let lang = /^tr/i.test(navigator.language) ? 'tr' : 'en';

export function getLang() { return lang; }
export function setLang(l) { lang = l === 'tr' ? 'tr' : 'en'; }
export function t(key, vars = {}) {
  const s = (strings[lang] && strings[lang][key]) ?? strings.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
export function locale() { return lang === 'tr' ? 'tr-TR' : 'en-US'; }
